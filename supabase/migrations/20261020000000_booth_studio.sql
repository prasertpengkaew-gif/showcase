-- AR Photo Booth Studio — database schema for Supabase.
--
-- Security model (read this before changing anything):
--   * The browser only ever holds the public "anon" key. Both tables have row level security
--     switched on with NO policies and no table grants, so the anon key cannot read or write
--     them directly.
--   * Everything the booth and the guest page may do goes through the SECURITY DEFINER functions
--     below, each of which checks what it needs to:
--       - the kiosk proves it belongs to an event with that event's secret kiosk token,
--       - a guest holds an unguessable 12-character photo code (60 bits) in the QR link.
--   * Photo files live in the public "photos" bucket under <event id>/<code>.jpg. Uploading is only
--     possible to a path that has been registered by a valid kiosk and not yet confirmed, and
--     listing the bucket is not allowed, so a file can only be fetched by someone who has its link.
--   * Admin work (creating events, exporting, purging) uses the service-role key from
--     scripts/booth-admin.mjs, never from the browser.

create table if not exists public.booth_events (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug ~ '^[a-z0-9][a-z0-9-]{2,39}$'),
  -- Secret that goes in the kiosk URL (?k=...). Two UUIDs = 244 random bits.
  kiosk_token text not null default replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', ''),
  name text not null check (char_length(name) between 1 and 80),
  -- Booth look and behaviour (frame, props, countdown, language ...). Validated again by the client.
  config jsonb not null default '{}'::jsonb,
  starts_at timestamptz,
  ends_at timestamptz,
  max_photos integer check (max_photos is null or max_photos > 0),
  retention_days integer not null default 30 check (retention_days between 1 and 365),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.booth_photos (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.booth_events (id) on delete cascade,
  -- Random code generated by the kiosk (base32, lower case). It is the guest's "key" to the photo.
  code text not null unique check (code ~ '^[a-z2-7]{12}$'),
  path text not null unique,
  status text not null default 'pending' check (status in ('pending', 'ready', 'deleted')),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null
);

create index if not exists booth_photos_event_idx on public.booth_photos (event_id, status);
create index if not exists booth_photos_expiry_idx on public.booth_photos (expires_at);

alter table public.booth_events enable row level security;
alter table public.booth_photos enable row level security;
revoke all on public.booth_events, public.booth_photos from anon, authenticated;

-- ---------------------------------------------------------------------------------------------
-- Internal helper: the event a kiosk token belongs to. `grace` lets photos that were queued while
-- the venue was offline still upload for a few days after the event ends.
-- ---------------------------------------------------------------------------------------------
create or replace function public.booth_find_event(p_slug text, p_token text, p_grace interval)
returns public.booth_events
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  e public.booth_events;
begin
  select * into e
  from public.booth_events b
  where b.slug = p_slug
    and b.kiosk_token = p_token
    and b.active
    and (b.starts_at is null or now() >= b.starts_at)
    and (b.ends_at is null or now() <= b.ends_at + p_grace);
  if not found then
    return null;
  end if;
  return e;
end;
$$;
revoke all on function public.booth_find_event(text, text, interval) from public, anon, authenticated;

-- ---------------------------------------------------------------------------------------------
-- Kiosk: configuration for an event. Returns null for a wrong token, an inactive event or when
-- the event is not running.
-- ---------------------------------------------------------------------------------------------
create or replace function public.booth_config(p_slug text, p_token text)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  e public.booth_events;
begin
  e := public.booth_find_event(p_slug, p_token, interval '0');
  if e.id is null then
    return null;
  end if;
  return jsonb_build_object(
    'slug', e.slug,
    'name', e.name,
    'config', e.config,
    'retentionDays', e.retention_days,
    'endsAt', e.ends_at
  );
end;
$$;

-- ---------------------------------------------------------------------------------------------
-- Kiosk: register a photo code before uploading the file. Safe to call again for the same code
-- (the offline queue retries), and enforces the event's photo limit.
-- ---------------------------------------------------------------------------------------------
create or replace function public.booth_register_photo(p_slug text, p_token text, p_code text)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  e public.booth_events;
  existing public.booth_photos;
  new_path text;
begin
  if p_code is null or p_code !~ '^[a-z2-7]{12}$' then
    raise exception 'invalid_code' using errcode = 'P0001';
  end if;
  e := public.booth_find_event(p_slug, p_token, interval '3 days');
  if e.id is null then
    raise exception 'invalid_event' using errcode = 'P0001';
  end if;

  select * into existing from public.booth_photos where code = p_code;
  if found then
    if existing.event_id <> e.id then
      raise exception 'invalid_code' using errcode = 'P0001';
    end if;
    return existing.path;
  end if;

  if e.max_photos is not null
     and (select count(*) from public.booth_photos where event_id = e.id and status <> 'deleted') >= e.max_photos then
    raise exception 'quota_reached' using errcode = 'P0001';
  end if;

  new_path := e.id::text || '/' || p_code || '.jpg';
  insert into public.booth_photos (event_id, code, path, expires_at)
  values (e.id, p_code, new_path, now() + make_interval(days => e.retention_days));
  return new_path;
end;
$$;

-- ---------------------------------------------------------------------------------------------
-- Kiosk: confirm that the file arrived, which makes the guest link work.
-- ---------------------------------------------------------------------------------------------
create or replace function public.booth_confirm_photo(p_slug text, p_token text, p_code text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  e public.booth_events;
  p public.booth_photos;
begin
  e := public.booth_find_event(p_slug, p_token, interval '3 days');
  if e.id is null then
    raise exception 'invalid_event' using errcode = 'P0001';
  end if;
  select * into p from public.booth_photos where code = p_code and event_id = e.id;
  if not found then
    raise exception 'invalid_code' using errcode = 'P0001';
  end if;
  if p.status = 'deleted' then
    return false;
  end if;
  if not exists (select 1 from storage.objects o where o.bucket_id = 'photos' and o.name = p.path) then
    raise exception 'not_uploaded' using errcode = 'P0001';
  end if;
  update public.booth_photos set status = 'ready' where id = p.id and status = 'pending';
  return true;
end;
$$;

-- ---------------------------------------------------------------------------------------------
-- Guest: look up a photo by the code in the QR link. Returns null when it does not exist, has
-- expired or was deleted; {"status":"pending"} while the booth is still uploading it.
-- ---------------------------------------------------------------------------------------------
create or replace function public.photo_get(p_code text)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  p public.booth_photos;
  e public.booth_events;
begin
  if p_code is null or p_code !~ '^[a-z2-7]{12}$' then
    return null;
  end if;
  select * into p from public.booth_photos where code = p_code and status <> 'deleted' and expires_at > now();
  if not found then
    return null;
  end if;
  if p.status = 'pending' then
    return jsonb_build_object('status', 'pending');
  end if;
  select * into e from public.booth_events where id = p.event_id;
  return jsonb_build_object(
    'status', 'ready',
    'path', p.path,
    'createdAt', p.created_at,
    'expiresAt', p.expires_at,
    'event', jsonb_build_object(
      'name', e.name,
      'subtitle', e.config ->> 'subtitle',
      'logoUrl', e.config ->> 'logoUrl',
      'accent', e.config ->> 'accent'
    )
  );
end;
$$;

-- ---------------------------------------------------------------------------------------------
-- Guest: delete "my" photo. Whoever holds the link may do this (the link is the key). The file
-- itself is removed by the next purge run (scripts/booth-admin.mjs purge).
-- ---------------------------------------------------------------------------------------------
create or replace function public.photo_delete(p_code text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_code is null or p_code !~ '^[a-z2-7]{12}$' then
    return false;
  end if;
  update public.booth_photos set status = 'deleted' where code = p_code and status <> 'deleted';
  return found;
end;
$$;

grant execute on function
  public.booth_config(text, text),
  public.booth_register_photo(text, text, text),
  public.booth_confirm_photo(text, text, text),
  public.photo_get(text),
  public.photo_delete(text)
to anon, authenticated;


insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values
  ('photos', 'photos', true, 5242880, array['image/jpeg']),
  ('branding', 'branding', true, 5242880, array['image/png', 'image/jpeg', 'image/webp', 'image/svg+xml'])
on conflict (id) do update
  set public = excluded.public,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

-- The storage policy cannot read booth_photos itself (it runs as the caller, who has no access),
-- so it asks this function, which does.
create or replace function public.booth_upload_allowed(p_path text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.booth_photos p
    join public.booth_events e on e.id = p.event_id
    where p.path = p_path
      and p.status = 'pending'
      and e.active
  );
$$;
grant execute on function public.booth_upload_allowed(text) to anon, authenticated;

drop policy if exists "booth: upload to a registered photo path" on storage.objects;
create policy "booth: upload to a registered photo path"
  on storage.objects
  for insert
  to anon, authenticated
  with check (bucket_id = 'photos' and public.booth_upload_allowed(name));

